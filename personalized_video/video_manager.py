"""Coordinate safe script generation, audio/video rendering, and reuse."""

import hashlib
import json
import logging
from pathlib import Path

import config
from personalized_video.script_generator import generate_script
from personalized_video.safety_checker import validate_script
from personalized_video.video_generator import render_video

logger = logging.getLogger("mh_chatbot.personalized_video")
_BASE_DIR = Path(__file__).resolve().parents[1]
_STATIC_DIR = (_BASE_DIR / "static").resolve()


def _signature(profile: dict, language: str = "en") -> str:
    """Return a stable, language-specific signature without raw user text."""
    compact = {
        "primary_problem": str(profile.get("primary_problem") or ""),
        "contexts": sorted(str(v) for v in (profile.get("contexts") or [])),
        "problem_tags": sorted(str(v) for v in (profile.get("problem_tags") or [])),
        "goals": sorted(str(v) for v in (profile.get("goals") or [])),
        "language": language,
    }
    return hashlib.sha256(json.dumps(compact, sort_keys=True).encode("utf-8")).hexdigest()[:32]


def _existing_video_resource(existing: dict, language: str):
    try:
        stored = Path(str(existing.get("video_path", "")))
        if stored.is_absolute():
            return None
        resolved = (_BASE_DIR / stored).resolve()
        resolved.relative_to(_STATIC_DIR)
        if not resolved.is_file() or resolved.stat().st_size < 1024:
            return None
        static_relative = resolved.relative_to(_STATIC_DIR).as_posix()
    except (OSError, ValueError, TypeError):
        return None

    return {
        "id": f"generated-{existing['id']}",
        "title": "Personalized educational video" if language == "en" else "आपके लिए शैक्षिक वीडियो",
        "description": "A previously generated educational video for this conversation." if language == "en" else "इस बातचीत के लिए पहले बनाया गया शैक्षिक वीडियो।",
        "resource_type": "video",
        "url": f"/static/{static_relative}",
        "source": "Generated by chatbot",
        "active": True,
        "generated": True,
        "language": language,
    }


def create_or_reuse_video(profile: dict, conversation_id=None, language: str = "en") -> dict:
    if language not in config.ALLOWED_VIDEO_LANGUAGES:
        raise ValueError("Video language must be 'en' or 'hi'.")

    signature = _signature(profile or {}, language)

    # Reuse only records that point to an existing file under static/.
    if conversation_id:
        try:
            import db
            existing = db.find_generated_video(conversation_id, signature)
            if existing:
                resource = _existing_video_resource(existing, language)
                if resource:
                    return resource
        except Exception:
            logger.warning("Could not look up an existing generated video.", exc_info=True)

    script_data = generate_script(profile or {}, language=language)
    script_text = "\n".join([script_data["title"], *script_data["sections"]])
    validation = validate_script(script_text)
    if not validation["safe"]:
        raise RuntimeError("Generated script did not pass the content check.")

    output_path = Path(render_video(script_data, config.VIDEO_GENERATION_DIR, language=language)).resolve()
    try:
        output_path.relative_to(_STATIC_DIR)
        relative = output_path.relative_to(_BASE_DIR).as_posix()
    except ValueError as exc:
        raise RuntimeError(
            "VIDEO_GENERATION_DIR must be inside this project's static/ directory so Flask can serve the MP4."
        ) from exc

    if not output_path.is_file() or output_path.stat().st_size < 1024:
        raise RuntimeError("Video generation did not produce a valid MP4 file.")

    if conversation_id:
        try:
            import db
            db.save_generated_video(
                conversation_id,
                signature,
                script_text,
                relative,
                "completed",
            )
        except Exception:
            logger.warning("Could not save generated-video metadata to the database.", exc_info=True)

    return {
        "id": f"generated-{signature}",
        "title": script_data["title"],
        "description": (
            "A personalized educational video with spoken narration. It is not a diagnosis or clinical treatment."
            if language == "en"
            else "यह बोलकर सुनाए गए वर्णन वाला व्यक्तिगत शैक्षिक वीडियो है। यह निदान या उपचार नहीं है।"
        ),
        "resource_type": "video",
        "url": f"/static/{output_path.relative_to(_STATIC_DIR).as_posix()}",
        "source": "Generated by chatbot",
        "active": True,
        "generated": True,
        "language": language,
    }
